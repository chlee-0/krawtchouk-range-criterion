def product(ar,ai,br,bi):
    n,k,m=len(ar),len(br),len(br[0])
    cr=[[sum(ar[i][t]*br[t][j]-ai[i][t]*bi[t][j] for t in range(k)) for j in range(m)] for i in range(n)]
